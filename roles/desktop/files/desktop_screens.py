"""Connected display settings, native configuration and timed confirmation."""
import json
import math
import re
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import uuid

import desktop_system as system

FIELD = 'screen.monitors'
MARKER = 'local settings_screens = root .. "/settings-screens.lua"'
TEST_SECONDS = 20
MODE = re.compile(r'([1-9][0-9]{1,4})x([1-9][0-9]{1,4})@([0-9]+(?:\.[0-9]+)?)(?:Hz)?')


def mode_parts(value):
    match = MODE.fullmatch(value) if isinstance(value, str) else None
    if not match or not 0 < float(match[3]) <= 1000:
        raise ValueError('Choose a supported resolution and refresh rate.')
    return int(match[1]), int(match[2]), float(match[3])


def shape(value):
    if not isinstance(value, list) or len(value) > 32:
        raise ValueError('Invalid screen configuration.')
    names = set()
    for item in value:
        if not isinstance(item, dict) or set(item) != {'name', 'mode', 'scale', 'transform', 'x', 'y'}:
            raise ValueError('Invalid screen configuration.')
        name = item['name']
        if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_.:-]{1,128}', name) or name in names:
            raise ValueError('Each display must have a unique output name.')
        names.add(name)
        width, height, _ = mode_parts(item['mode'])
        scale = item['scale']
        if type(scale) not in (int, float) or not math.isfinite(scale) or not 1 <= scale <= 4:
            raise ValueError('Scale must be between 100% and 400%.')
        if any(abs(size / scale - round(size / scale)) > 0.01 for size in (width, height)):
            raise ValueError('Choose a scale that produces whole logical pixels for this resolution.')
        if type(item['transform']) is not int or not 0 <= item['transform'] <= 7:
            raise ValueError('Choose a supported rotation.')
        if any(type(item[key]) is not int or not -65535 <= item[key] <= 65535 for key in ('x', 'y')):
            raise ValueError('Monitor positions must be whole pixels between -65535 and 65535.')


def observe():
    if not system.in_session():
        return {'values': [], 'catalog': [], 'error': 'Screen configuration is available inside a Hyprland session.'}
    try:
        monitors = system.monitors()
        values, catalog = [], []
        for monitor in sorted(monitors, key=lambda item: item['name']):
            if monitor.get('disabled') or monitor.get('mirrorOf', 'none') not in ('none', None, ''):
                continue
            modes = list(dict.fromkeys(mode.removesuffix('Hz') for mode in monitor.get('availableModes', []) if MODE.fullmatch(mode)))
            current = f"{monitor['width']}x{monitor['height']}@{monitor['refreshRate']:.2f}"
            if current not in modes:
                modes.insert(0, current)
            values.append({'name': monitor['name'], 'mode': current, 'scale': monitor['scale'],
                           'transform': monitor.get('transform', 0), 'x': monitor['x'], 'y': monitor['y']})
            catalog.append({'name': monitor['name'], 'description': monitor.get('description', monitor['name']), 'modes': modes})
        return {'values': values, 'catalog': catalog, 'error': ''}
    except (OSError, RuntimeError, ValueError, KeyError, TypeError, subprocess.SubprocessError) as error:
        return {'values': [], 'catalog': [], 'error': 'Cannot read connected displays: ' + str(error)}


def validate(value, observed):
    shape(value)
    if observed['error']:
        raise ValueError(observed['error'])
    available = {item['name']: item for item in observed['catalog']}
    if not value or {item['name'] for item in value} != set(available):
        raise ValueError('Connected displays changed. Revert to reload them before applying.')
    rectangles = []
    for item in value:
        if item['mode'] not in available[item['name']]['modes']:
            raise ValueError('The selected mode is no longer available on ' + item['name'] + '.')
        width, height, _ = mode_parts(item['mode'])
        if item['transform'] % 2:
            width, height = height, width
        x, y = item['x'], item['y']
        rectangle = (x, y, x + width / item['scale'], y + height / item['scale'])
        if any(x < right and rectangle[2] > left and y < bottom and rectangle[3] > top
               for left, top, right, bottom in rectangles):
            raise ValueError('Displays overlap. Adjust their positions in logical pixels.')
        rectangles.append(rectangle)


def text(value):
    shape(value)
    lines = ['-- Generated by desktop-settings.']
    for item in value:
        spec = {'output': item['name'], 'mode': item['mode'], 'scale': item['scale'],
                'transform': item['transform'], 'position': f"{item['x']}x{item['y']}"}
        lines.append('hl.monitor({' + ','.join(key + '=' + json.dumps(value) for key, value in spec.items()) + '})')
    return '\n'.join(lines) + '\n'


def prepare(root, content):
    source = (root / 'hyprland.lua').read_text()
    if source.count(MARKER) != 1:
        raise RuntimeError('Reapply the desktop profile before changing screen configuration.')
    with tempfile.TemporaryDirectory(prefix='.screen-validation-', dir=root) as folder:
        path = Path(folder)
        (path / 'settings-screens.lua').write_text(content)
        candidate = path / 'hyprland.lua'
        candidate.write_text(source.replace(MARKER, 'local settings_screens = ' + json.dumps(str(path / 'settings-screens.lua'))))
        system.command([str(root / 'bin/validate-config'), str(candidate)], timeout=20)


def reload(value):
    system.command(['hyprctl', 'reload'])
    error = system.command(['hyprctl', 'configerrors']).strip()
    if error:
        raise RuntimeError('The compositor rejected the screen configuration: ' + error)
    wait_for(value)


def wait_for(value, subset=False):
    deadline = time.monotonic() + 3
    while True:
        actual = observe()
        if subset:
            names = {item['name'] for item in value}
            actual['values'] = [item for item in actual['values'] if item['name'] in names]
        if matches(value, actual['values']) and not actual['error']:
            return
        if time.monotonic() >= deadline:
            raise RuntimeError('The selected screen configuration did not take effect. Check personal monitor overrides.')
        time.sleep(0.15)


def matches(expected, actual):
    actual = {item['name']: item for item in actual}
    for item in expected:
        other = actual.get(item['name'])
        if not other or any(item[key] != other[key] for key in ('x', 'y', 'transform')):
            return False
        width, height, rate = mode_parts(item['mode'])
        other_width, other_height, other_rate = mode_parts(other['mode'])
        if (width, height) != (other_width, other_height) or abs(rate - other_rate) > 0.1 or abs(item['scale'] - other['scale']) > 0.01:
            return False
    return len(expected) == len(actual)


def restore(value):
    # Reload restored files first, then reinstate the pre-test runtime geometry.
    system.command(['hyprctl', 'reload'])
    connected = {item['name'] for item in system.monitors()}
    previous = [item for item in value if item['name'] in connected]
    system.command(['hyprctl', 'eval', text(previous)])
    wait_for(previous, subset=True)


def status(root):
    try:
        pending = json.loads((root / '.screen-test.json').read_text())
        return {'token': pending['token'], 'seconds': max(0, math.ceil(pending['deadline'] - time.time()))}
    except (OSError, ValueError, KeyError):
        return None


def decide(root, token, keep):
    pending = status(root)
    if not pending or pending['token'] != token or not pending['seconds'] or type(keep) is not bool:
        raise ValueError('The screen confirmation has expired.')
    from desktop_settings import atomic_save
    atomic_save(root / '.screen-decision.json', {'token': token, 'keep': keep})


def start_guard(root):
    # Survives the shell/helper exiting during a display test. The shared lock
    # prevents recovery from racing an Apply that is still running.
    return subprocess.Popen([sys.executable, str(root / 'bin/desktop-settings'), 'screen-watch'],
                            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                            close_fds=True, start_new_session=True)


def confirm(root):
    from desktop_settings import atomic_save
    token = uuid.uuid4().hex
    deadline = time.monotonic() + TEST_SECONDS
    atomic_save(root / '.screen-test.json', {'token': token, 'deadline': time.time() + TEST_SECONDS})
    try:
        while time.monotonic() < deadline:
            try:
                decision = json.loads((root / '.screen-decision.json').read_text())
                if decision.get('token') == token:
                    if decision.get('keep') is True:
                        return
                    break
            except (OSError, ValueError):
                pass
            time.sleep(0.1)
        raise RuntimeError('Screen changes were reverted because they were not kept.')
    finally:
        (root / '.screen-test.json').unlink(missing_ok=True)
        (root / '.screen-decision.json').unlink(missing_ok=True)
